def _طلب_بيانات_حقيقي(path, params=None, مهلة=8):
    """طبقة HTTP موحدة مع مهلة قصيرة وفشل آمن."""
    try:
        import requests
    except ImportError as exc:
        return None, {"نجاح": False, "الخطأ": "مكتبة requests غير مثبتة.", "تفصيل": str(exc)}
    key = مفتاح_البيانات_الحية()
    if not key:
        return None, {"نجاح": False, "الخطأ": "مفتاح EGXAPI غير موجود."}
    headers = {"Authorization": f"Bearer {key}", "Accept": "application/json"}
    started = time.perf_counter()
    try:
        r = requests.get(f"{رابط_مصدر_البيانات}{path}", headers=headers, params=params or {}, timeout=مهلة)
        elapsed = round((time.perf_counter() - started) * 1000, 2)
        if r.status_code >= 400:
            return None, {"نجاح": False, "الرمز": r.status_code, "الخطأ": r.text[:500], "زمن_الاستجابة_مللي": elapsed}
        return r.json(), {"نجاح": True, "الرمز": r.status_code, "زمن_الاستجابة_مللي": elapsed}
    except Exception as exc:
        return None, {"نجاح": False, "الخطأ": str(exc), "زمن_الاستجابة_مللي": round((time.perf_counter()-started)*1000, 2)}


def _استخراج_قائمة(payload):
    if isinstance(payload, list):
        return payload
    if not isinstance(payload, dict):
        return []
    for key in ("data", "bars", "quotes", "results", "items", "candles"):
        value = payload.get(key)
        if isinstance(value, list):
            return value
    return []


def جلب_بيانات_مؤشر_حية(الرمز, المسار=None):
    """موصل المؤشرات منفصل عن موصل الأسهم لتجنب خلط دلالات المصدر."""
    المسار = المسار or os.getenv("EGX_INDEX_QUOTES_PATH", os.getenv("EGX_QUOTES_PATH", "/v2/market-data/quotes"))
    payload, meta = _طلب_بيانات_حقيقي(المسار, {"symbol": الرمز, "type": "index"})
